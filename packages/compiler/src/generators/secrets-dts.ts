/**
 * Generates a .d.ts augmenting @kici-dev/sdk's KnownSecretKeys and
 * ContextSecrets, so `ctx.secrets.get()` and `ctx.secrets.expose()` key names
 * autocomplete and type-check per context.
 */

export interface ContextMetadata {
  name: string;
  keys: string[];
}

export interface GenerateSecretsDtsOptions {
  contexts: ContextMetadata[];
  /**
   * Where the key names came from, written to the `// Source:` header
   * (`orchestrator <url>`, `Platform org <id>`, `local files`).
   */
  sourceLabel: string;
  /**
   * An offline stub, written when no orchestrator, Platform login or local
   * secret file supplied key names. The header names it a stub so a reader can
   * tell it from a real snapshot; the caller passes `contexts: []`.
   */
  offline?: boolean;
}

function isValidIdentifier(name: string): boolean {
  return /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(name);
}

function escapeQuotes(s: string): string {
  return s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function formatProperty(name: string): string {
  return isValidIdentifier(name) ? name : `'${escapeQuotes(name)}'`;
}

/** Key → the contexts that provide it. */
function buildKeySourceMap(contexts: ContextMetadata[]): Map<string, string[]> {
  const map = new Map<string, string[]>();
  for (const env of contexts) {
    for (const key of env.keys) {
      const sources = map.get(key);
      if (sources) {
        sources.push(env.name);
      } else {
        map.set(key, [env.name]);
      }
    }
  }
  return map;
}

export function generateSecretsDts(options: GenerateSecretsDtsOptions): string {
  const { contexts, sourceLabel, offline } = options;
  const lines: string[] = [];

  // No timestamp, deliberately: regenerating via `kici types` / `kici compile`
  // must never produce a spurious diff.
  lines.push('// @generated by kici types -- DO NOT EDIT');
  if (offline) {
    lines.push(
      '// Source: offline stub -- no orchestrator, Platform or local secret files; no known secret keys',
    );
  } else {
    lines.push(`// Source: ${sourceLabel}`);
  }
  lines.push('// Run `kici types` to refresh');
  lines.push('');

  lines.push("declare module '@kici-dev/sdk' {");

  // KnownSecretKeys: every key across all contexts.
  const keySourceMap = buildKeySourceMap(contexts);
  lines.push('  interface KnownSecretKeys {');
  for (const [key, sources] of keySourceMap) {
    lines.push(`    /** From context: ${sources.join(', ')} */`);
    lines.push(`    ${formatProperty(key)}: string;`);
  }
  lines.push('  }');

  lines.push('');

  // ContextSecrets: each context's keys as a union.
  lines.push('  interface ContextSecrets {');
  for (const env of contexts) {
    if (env.keys.length === 0) {
      lines.push(`    ${formatProperty(env.name)}: never;`);
    } else {
      const keyUnion = env.keys.map((k) => `'${escapeQuotes(k)}'`).join(' | ');
      lines.push(`    ${formatProperty(env.name)}: ${keyUnion};`);
    }
  }
  lines.push('  }');

  lines.push('}');
  lines.push('');

  // The top-level export makes the file a module, so `declare module` augments
  // the SDK instead of an ambient declaration shadowing the whole module.
  lines.push('export {};');
  lines.push('');

  return lines.join('\n');
}
